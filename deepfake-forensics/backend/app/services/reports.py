"""PDF analysis reports (ReportLab). Sensitive EXIF values are never included."""
from __future__ import annotations

import io
from pathlib import Path
from typing import Any

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import Image as RLImage
from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

from app.core.config import APP_VERSION


def _p(text: Any, style) -> Paragraph:
    s = str(text if text is not None else "—")
    s = s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    return Paragraph(s, style)


def _img(path: Path | None, max_w: float, max_h: float):
    if path is None or not path.is_file():
        return None
    from PIL import Image

    with Image.open(path) as im:
        w, h = im.size
    s = min(max_w / w, max_h / h)
    return RLImage(str(path), width=w * s, height=h * s)


def _table(rows: list[list[Any]], styles, col_widths=None) -> Table:
    body = styles["BodyText"]
    data = [[_p(c, body) for c in r] for r in rows]
    t = Table(data, colWidths=col_widths, hAlign="LEFT")
    t.setStyle(TableStyle([
        ("GRID", (0, 0), (-1, -1), 0.25, colors.HexColor("#c8cdd4")),
        ("BACKGROUND", (0, 0), (0, -1), colors.HexColor("#f1f3f5")),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("FONTSIZE", (0, 0), (-1, -1), 8),
    ]))
    return t


def build_analysis_report(payload: dict[str, Any], files: dict[str, Path | None]) -> bytes:
    buf = io.BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=A4, leftMargin=16 * mm, rightMargin=16 * mm, topMargin=14 * mm, bottomMargin=14 * mm, title=f"Analysis report {payload['id']}")
    ss = getSampleStyleSheet()
    small = ParagraphStyle("small", parent=ss["BodyText"], fontSize=8, leading=10)
    warn = ParagraphStyle("warn", parent=ss["BodyText"], fontSize=9, leading=11, textColor=colors.HexColor("#9a3412"))
    story: list[Any] = []
    story.append(_p("Deepfake Image Detection and Forensic Analysis Platform — Analysis Report", ss["Title"]))
    story.append(_p(f"Report generated by platform version {APP_VERSION}. Analysis ID: {payload['id']}", small))
    story.append(Spacer(1, 4 * mm))

    for w in payload.get("warnings", []):
        story.append(_p("WARNING: " + w, warn))
    story.append(_p(payload.get("disclaimer", ""), warn))
    story.append(Spacer(1, 3 * mm))

    m = payload.get("model", {})
    story.append(_p("Model result", ss["Heading2"]))
    story.append(_table([
        ["Predicted class", payload["prediction"]],
        ["Fake score (model output for FAKE)", f"{payload['fake_score']:.4f}"],
        ["Decision threshold", f"{payload['threshold']:.4f} — {payload.get('threshold_source', '')}"],
        ["Detection track", payload.get("track_label", payload["track"])],
        ["Model", f"{m.get('display_name')} [{m.get('model_id')}]"],
        ["Model version", m.get("version")],
        ["Trained on (dataset ids)", ", ".join(m.get("trained_on") or []) or "—"],
        ["Inference time", f"{payload['inference_ms']:.1f} ms on {payload.get('device', '')}"],
        ["Timestamp (UTC)", payload["created_at"]],
    ], ss, [62 * mm, 116 * mm]))
    story.append(_p(payload.get("score_note", ""), small))
    story.append(Spacer(1, 3 * mm))

    imgs = [(_img(files.get("original"), 56 * mm, 56 * mm), "Uploaded image"), (_img(files.get("gradcam"), 56 * mm, 56 * mm), "Grad-CAM overlay (model input view)"), (_img(files.get("spectrum"), 56 * mm, 56 * mm), "Fourier log-magnitude spectrum")]
    imgs = [(i, c) for i, c in imgs if i is not None]
    if imgs:
        story.append(_p("Images", ss["Heading2"]))
        t = Table([[i for i, _ in imgs], [_p(c, small) for _, c in imgs]], hAlign="LEFT")
        t.setStyle(TableStyle([("VALIGN", (0, 0), (-1, -1), "TOP")]))
        story.append(t)
        ex = payload.get("explanation", {})
        if ex.get("available"):
            story.append(_p(f"Grad-CAM explains class {ex.get('explained_class')} at layer {ex.get('target_layer')}. {ex.get('resolution_note', '')} {ex.get('note', '')}", small))
        story.append(Spacer(1, 3 * mm))

    f = payload.get("forensics", {})
    pr = f.get("properties", {})
    story.append(_p("Measured image properties (direct observations, not model inferences)", ss["Heading2"]))
    rows = [
        ["Format / MIME", f"{pr.get('format')} / {pr.get('mime_type')}"],
        ["Dimensions", f"{pr.get('width')} x {pr.get('height')} px ({pr.get('megapixels')} MP)"],
        ["File size", f"{pr.get('file_size_bytes'):,} bytes" if pr.get("file_size_bytes") else "—"],
        ["Color mode", pr.get("color_mode")],
        ["Alpha channel", pr.get("has_alpha")],
        ["ICC profile present", pr.get("icc_profile_present")],
        ["SHA-256", payload.get("image", {}).get("sha256")],
    ]
    jp = f.get("jpeg")
    if jp:
        qe = jp.get("quality_estimate") or {}
        rows += [["JPEG chroma subsampling", jp.get("chroma_subsampling")], ["JPEG progressive", jp.get("progressive")], ["JPEG quality estimate", f"{qe.get('estimated_quality')} ({qe.get('method', '')})"]]
    story.append(_table(rows, ss, [62 * mm, 116 * mm]))
    exif = f.get("exif", {})
    story.append(Spacer(1, 2 * mm))
    if exif.get("present"):
        tags = list(exif.get("tags", {}).items())[:25]
        if tags:
            story.append(_p("EXIF metadata (first 25 non-sensitive tags)", ss["Heading3"]))
            story.append(_table([[k, v] for k, v in tags], ss, [62 * mm, 116 * mm]))
        if exif.get("redacted"):
            story.append(_p("Redacted (present but not shown): " + ", ".join(exif["redacted"]), small))
    else:
        story.append(_p("No EXIF metadata present. Missing metadata does not indicate that an image is fake.", small))
    obs = f.get("observations", [])
    if obs:
        story.append(_p("Observations", ss["Heading3"]))
        for o in obs:
            story.append(_p(f"• [{o['kind']}] {o['text']} — {o['caveat']}", small))

    story.append(Spacer(1, 3 * mm))
    story.append(_p("Limitations", ss["Heading2"]))
    for line in (
        "The detector is a statistical classifier trained on specific datasets; performance can degrade on unseen generators, manipulation methods, compression levels and image sources.",
        "Scores are not calibrated probabilities unless stated. A threshold chosen on validation data trades false positives against false negatives.",
        "Grad-CAM and frequency visualizations are qualitative aids and do not uniquely identify manipulated images.",
        "This report does not identify any person and must not be used as legal or forensic proof.",
    ):
        story.append(_p("• " + line, small))
    doc.build(story)
    return buf.getvalue()
